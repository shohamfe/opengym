#!/usr/bin/env node
// Regenerates the data the gym-mcp Edge Function bundles (supabase/functions/gym-mcp/_gen/):
//  - catalog.js: [id, name, equipment, target, bodypart] for every built-in exercise, from
//    frontend/src/lib/exercises-data.js (the instructions and media are not needed server side).
//  - pregnancy.js + pregnancy-labels.js: copied unchanged from frontend/src/lib/ when they exist
//    (one label function for the app and the AI). Before those land, pregnancy-labels.js is
//    generated in the same shape from the coach's JSON, and the hand-written fallback
//    _gen/pregnancy.js (same exports) stays in place.
//
//   node scripts/build-mcp-data.mjs [path/to/pregnancy-labels.json]
//
// Re-run after any change to the exercise list or the pregnancy labels, then redeploy gym-mcp.

import { existsSync, readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'frontend', 'src', 'lib')
const out = join(root, 'supabase', 'functions', 'gym-mcp', '_gen')
mkdirSync(out, { recursive: true })
const HEAD = '// GENERATED by scripts/build-mcp-data.mjs. Do not edit by hand.\n'

const { EXDB } = await import(pathToFileURL(join(lib, 'exercises-data.js')).href)
const rows = EXDB.map(e => [e.id, e.n, e.eq, e.tg, e.bp])
writeFileSync(join(out, 'catalog.js'), HEAD + 'export const CATALOG = [\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n')
console.log(`catalog.js: ${rows.length} exercises`)

if (existsSync(join(lib, 'pregnancy.js')) && existsSync(join(lib, 'pregnancy-labels.js'))) {
  for (const f of ['pregnancy.js', 'pregnancy-labels.js']) {
    const src = readFileSync(join(lib, f), 'utf8')
    // Deno bundles only what the function imports; anything beyond the pair would break the deploy.
    const bad = [...src.matchAll(/from\s+['"]([^'"]+)['"]/g)].map(m => m[1]).filter(p => p !== './pregnancy-labels.js')
    if (bad.length) throw new Error(`${f} imports ${bad.join(', ')}; the Edge Function copy must import nothing else`)
    copyFileSync(join(lib, f), join(out, f))
  }
  console.log('pregnancy.js + pregnancy-labels.js: copied from frontend/src/lib')
} else {
  const src = process.argv[2] || [join(root, 'data', 'pregnancy-labels.json'), '/mnt/project-files/multi-user/pregnancy-labels.json'].find(existsSync)
  if (!src) throw new Error('pregnancy-labels.json not found; pass its path')
  const J = JSON.parse(readFileSync(src, 'utf8'))
  const L = { avoid: 'a', caution: 'c', recommended: 'r', ok: 'o' }
  const letters = t => t.map(x => L[x]).join('')
  const PREG = {}
  for (const [id, e] of Object.entries(J)) {
    if (id.startsWith('_') || !Array.isArray(e.t)) continue
    const t = letters(e.t)
    const u = e.tu ? letters(e.tu) : ''
    if (t === 'ooo' && (!u || u === 'ooo')) continue      // absent = ok in all trimesters
    PREG[id] = `${e.rule || e.label}:${t}${u && u !== t ? ':' + u : ''}`
  }
  const RULES = Object.fromEntries(Object.entries(J._rules).map(([k, v]) => [k, v.reason]))
  const NC = Object.values(J._profiles?.not_consistent || {})[0]?.reason || ''
  writeFileSync(join(out, 'pregnancy-labels.js'), HEAD +
    `export const RULES = ${JSON.stringify(RULES, null, 1)}\n` +
    `export const NC_REASON = ${JSON.stringify(NC)}\n` +
    `export const PREG = ${JSON.stringify(PREG)}\n`)
  console.log(`pregnancy-labels.js: ${Object.keys(PREG).length} labelled ids from ${src} (fallback pregnancy.js kept)`)
}
