#!/usr/bin/env node
// Regenerates frontend/src/lib/pregnancy-labels.js from the coach's pregnancy-labels.json
// (built by the coach's pregnancy-labels.py). Keeps only what the app reads, compactly:
//
//   node scripts/gen-pregnancy-labels.mjs [path-to-pregnancy-labels.json]
//
// Default input: scripts/pregnancy-labels.json (a copy of the coach's file).

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(readFileSync(process.argv[2] || join(root, 'scripts', 'pregnancy-labels.json'), 'utf8'))
const L = { avoid: 'a', caution: 'c', recommended: 'r', ok: 'o' }

// The 12 pregnancy built-ins (exercises-data.js 9002-9013) are not in the coach's dataset run;
// they were picked as recommended (coach-pregnancy.md section 4), so they are labelled here.
const BUILTINS = ['9002', '9003', '9004', '9005', '9006', '9007', '9008', '9009', '9010', '9011', '9012', '9013']

const RULES = {}
for (const [k, v] of Object.entries(src._rules)) RULES[k] = v.reason
const nc = Object.values(src._profiles.not_consistent)
const NC_REASON = nc[0].reason
if (nc.some(r => r.reason !== NC_REASON)) throw new Error('not_consistent reasons differ; extend the format')

const PREG = {}
for (const [id, e] of Object.entries(src)) {
  if (id.startsWith('_')) continue
  const t = e.t.map(x => L[x]).join('')
  const tu = e.tu ? e.tu.map(x => L[x]).join('') : ''
  if (t === 'ooo' && !tu) continue
  if (!RULES[e.rule]) throw new Error(id + ': unknown rule ' + e.rule)
  PREG[id] = e.rule + ':' + t + (tu ? ':' + tu : '')
}
for (const id of BUILTINS) PREG[id] = 'recommended:rrr'

const out = '// generated by scripts/gen-pregnancy-labels.mjs from pregnancy-labels.json — do not edit\n' +
  '// PREG[id] = "rule:T1T2T3[:U1U2U3]" (a avoid, c caution, r recommended, o ok); U = labels when\n' +
  '// the user was not a consistent lifter before pregnancy. Ids not listed are ok throughout.\n' +
  '// No imports: the MCP edge function (Deno) reuses this file as is.\n' +
  'export const RULES = ' + JSON.stringify(RULES, null, 0) + '\n' +
  'export const NC_REASON = ' + JSON.stringify(NC_REASON) + '\n' +
  'export const PREG = ' + JSON.stringify(PREG) + '\n'
writeFileSync(join(root, 'frontend', 'src', 'lib', 'pregnancy-labels.js'), out)
console.log(Object.keys(PREG).length + ' labelled exercises')
